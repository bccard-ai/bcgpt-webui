async def _audit_retention_task(app: FastAPI) -> None:
    """Periodically purge expired audit logs based on retention config."""
    while True:
        await asyncio.sleep(86400)
        try:
            retention_days = int(
                _get_config_value(app.state.config.AUDIT_RETENTION_DAYS)
            )
            from bcgpt.models.audit_log import AuditLogs

            deleted = AuditLogs.purge_expired(retention_days)
            if deleted > 0:
                log.info(
                    f"Auto-purged {deleted} audit logs older than {retention_days} days"
                )
        except Exception as e:
            log.error(f"Failed to auto-purge audit logs: {e}")


async def _chat_retention_task(app: FastAPI) -> None:
    """Periodically enforce chat data retention (anonymize or purge) — 2.4."""
    while True:
        await asyncio.sleep(86400)
        try:
            days = int(_get_config_value(app.state.config.CHAT_RETENTION_DAYS) or 0)
            if days <= 0:
                continue
            from bcgpt.models.chats import Chats

            if _get_config_value(app.state.config.CHAT_RETENTION_ANONYMIZE):
                n = Chats.anonymize_chats_older_than(days)
                if n:
                    log.info(f"Anonymized {n} chats older than {days} days")
            else:
                n = Chats.delete_chats_older_than(days)
                if n:
                    log.info(f"Purged {n} chats older than {days} days")
        except Exception as e:
            log.error(f"Failed chat retention task: {e}")


async def _compliance_retention_task(app: FastAPI) -> None:
    """Daily compliance maintenance: AIIA expiry check + provenance purge."""
    while True:
        await asyncio.sleep(86400)
        try:
            if not _get_config_value(app.state.config.COMPLIANCE_ENABLED):
                continue

            if _get_config_value(app.state.config.COMPLIANCE_AIIA_ENABLED):
                from bcgpt.compliance.models.aiia import AIIARecords

                expired = AIIARecords.get_expired()
                if expired:
                    log.warning(
                        "AIIA: %d impact assessments have expired and need re-assessment",
                        len(expired),
                    )

            if _get_config_value(app.state.config.COMPLIANCE_PROVENANCE_ENABLED):
                from bcgpt.compliance.models.provenance import AIRAGProvenances

                purged = AIRAGProvenances.purge_expired()
                if purged:
                    log.info("Provenance: purged %d expired records", purged)

        except Exception as e:
            log.error(f"Failed compliance retention task: {e}")


