@asynccontextmanager
async def lifespan(app: FastAPI):
    start_logger()

    # Validate configuration
    from bcgpt.settings import validate_settings

    try:
        warnings = validate_settings()
        for w in warnings:
            log.warning(f"Config warning: {w}")
    except ValueError as e:
        log.error(f"Configuration validation failed: {e}")
        if os.environ.get("ENV", "prod") != "dev":
            raise

    if RESET_CONFIG_ON_START:
        reset_config()

    if LICENSE_KEY:
        get_license_data(app, LICENSE_KEY)

    init_providers(app.state.config)

    # Seed default LLM model pricing for FinOps cost computation (2.1), opt-in.
    if app.state.config.TOKEN_USAGE_PERSIST_ENABLED:
        try:
            from bcgpt.models.token_usage import ModelPricings

            seeded = ModelPricings.seed_defaults()
            if seeded:
                log.info("Seeded %d default model_pricing rows", seeded)
        except Exception as e:
            log.warning("Could not seed model pricing: %s", e)

    # Seed curated built-in skills (idempotent).
    try:
        from bcgpt.utils.skill_seeds import seed_builtin_skills

        seeded_skills = seed_builtin_skills()
        if seeded_skills:
            log.info("Seeded %d built-in skills", seeded_skills)
    except Exception as e:
        log.warning("Built-in skill seeding skipped: %s", e)

    # Load the persisted GraphRAG knowledge graph into memory (3.1), opt-in.
    if app.state.config.RAG_GRAPH_ENABLED:
        try:
            from bcgpt.retrieval.graph.graph_builder import load_graph_from_db

            nodes = load_graph_from_db()
            log.info("Loaded knowledge graph from DB (%d nodes)", nodes)
        except Exception as e:
            log.warning("Could not load knowledge graph: %s", e)

    # --- MCP built-in servers (in-process Streamable HTTP) ---
    # FastAPI does not propagate ASGI lifespan to mounted Starlette sub-apps, so
    # each built-in's session_manager.run() must be entered here via AsyncExitStack
    # (else RuntimeError "Task group is not initialized"). Built-ins are loopback
    # only — do NOT expose /mcp/builtin/* through a public reverse proxy.
    import contextlib as _contextlib

    from bcgpt.mcpbridge.builtins import fetch as _builtin_fetch
    from bcgpt.mcpbridge.builtins import time as _builtin_time

    app.state.mcp_exit_stack = _contextlib.AsyncExitStack()
    _builtin_factories = {
        _builtin_time.BUILTIN_NAME: _builtin_time.create_server,
        _builtin_fetch.BUILTIN_NAME: _builtin_fetch.create_server,
    }
    for _name in list(
        getattr(app.state.config.MCP_BUILTINS_ENABLED, "value", []) or []
    ):
        _factory = _builtin_factories.get(_name)
        if _factory is None:
            continue
        try:
            _mcp_app = _factory()
            _asgi = _mcp_app.streamable_http_app()  # materialize session_manager
            app.mount(f"/mcp/builtin/{_name}", _asgi)
            await app.state.mcp_exit_stack.enter_async_context(
                _mcp_app.session_manager.run()
            )
            log.info("Started built-in MCP server: %s", _name)
        except Exception as e:
            log.warning("Failed to start built-in MCP %s: %s", _name, e)

    # Background tasks
    cleanup_task = asyncio.create_task(periodic_usage_pool_cleanup())
    audit_task = asyncio.create_task(_audit_retention_task(app))
    chat_retention_task = asyncio.create_task(_chat_retention_task(app))
    compliance_task = asyncio.create_task(_compliance_retention_task(app))

    yield

    # ── Graceful shutdown ──────────────────────────────────────────────
    try:
        await app.state.mcp_exit_stack.aclose()
    except Exception as e:
        log.warning("MCP built-in shutdown error: %s", e)
    for task in (cleanup_task, audit_task, chat_retention_task, compliance_task):
        task.cancel()
        try:
            await task
        except asyncio.CancelledError:
            pass

    await close_client_session()

    for _cleanup in (
        _shutdown_vector_db,
        _shutdown_telemetry,
        _shutdown_db_engine,
    ):
        try:
            _cleanup()
        except Exception:
            pass


