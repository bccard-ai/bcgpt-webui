# Middleware setup
# =========================================================================


def _setup_middleware(app: FastAPI) -> None:
    """Register the full middleware chain."""

    # Class-based middleware (added in LIFO order — last added runs first)
    app.add_middleware(RedirectMiddleware)
    app.add_middleware(SecurityHeadersMiddleware)
    app.add_middleware(InMemoryRateLimiter)
    app.add_middleware(
        CSRFProtectionMiddleware,
        exempt_prefixes=[
            "/ws/",
            "/oauth/",
            "/api/v1/audio/",
            "/health",
            "/healthz",
            "/livez",
            "/readyz",
        ],
    )

    # Function-based middleware
    @app.middleware("http")
    async def commit_session_after_request(request: Request, call_next):
        response = await call_next(request)
        Session.commit()
        return response

    @app.middleware("http")
    async def check_url(request: Request, call_next):
        start_time = int(time.time())
        request.state.enable_api_key = app.state.config.ENABLE_API_KEY
        response = await call_next(request)
        response.headers["X-Process-Time"] = str(int(time.time()) - start_time)
        return response

    @app.middleware("http")
    async def inspect_websocket(request: Request, call_next):
        if (
            "/ws/socket.io" in request.url.path
            and request.query_params.get("transport") == "websocket"
        ):
            upgrade = (request.headers.get("Upgrade") or "").lower()
            connection = (request.headers.get("Connection") or "").lower().split(",")
            if upgrade != "websocket" or "upgrade" not in connection:
                return JSONResponse(
                    status_code=status.HTTP_400_BAD_REQUEST,
                    content={"detail": "Invalid WebSocket upgrade request"},
                )
        return await call_next(request)

    # CORS
    if CORS_ALLOW_ORIGIN and CORS_ALLOW_ORIGIN != [""]:
        origins = CORS_ALLOW_ORIGIN
        if "*" in origins:
            log.warning(
                "CORS: Wildcard origin ('*') is configured with allow_credentials=True. "
                "This combination is rejected by browsers. Removing wildcard and falling back to Same-Origin."
            )
            origins = [o for o in origins if o != "*"]
        if origins:
            app.add_middleware(
                CORSMiddleware,
                allow_origins=origins,
                allow_credentials=True,
                allow_methods=["GET", "POST", "PUT", "DELETE", "PATCH", "OPTIONS"],
                allow_headers=[
                    "Authorization",
                    "Content-Type",
                    "Accept",
                    "X-CSRF-Token",
                    "X-Request-ID",
                ],
            )
    else:
        log.info(
            "CORS: No origins configured (CORS_ALLOW_ORIGIN is empty). Same-origin policy enforced."
        )

    # Session middleware (required by authlib for OAuth)
    if len(OAUTH_PROVIDERS) > 0:
        app.add_middleware(
            SessionMiddleware,
            secret_key=BCGPT_SECRET_KEY,
            session_cookie="oui-session",
            same_site=BCGPT_SESSION_COOKIE_SAME_SITE,
            https_only=BCGPT_SESSION_COOKIE_SECURE,
        )

    # Audit logging (added last so it wraps everything)
    app.add_middleware(AuditLoggingMiddleware, starlette_app=app)


