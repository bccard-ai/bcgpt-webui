# ── Kubernetes probes ──────────────────────────────────────────────────


def _db_health_check():
    with engine.connect() as conn:
        conn.execute(text("SELECT 1"))


def _qdrant_health_check():
    from bcgpt.retrieval.vector.connector import VECTOR_DB_CLIENT

    if (
        VECTOR_DB_CLIENT
        and hasattr(VECTOR_DB_CLIENT, "client")
        and VECTOR_DB_CLIENT.client
    ):
        VECTOR_DB_CLIENT.client.get_collections()
        return "ok"
    return "not_configured"


def _redis_health_check():
    if not REDIS_URL:
        return "not_configured"
    import redis as redis_lib

    r = redis_lib.Redis.from_url(str(REDIS_URL), socket_connect_timeout=3)
    try:
        r.ping()
        return "ok"
    finally:
        r.close()


@app.get("/healthz")
async def healthz():
    """Kubernetes liveness probe — process is alive."""
    return {"status": "alive"}


@app.get("/livez")
async def livez():
    """Kubernetes liveness probe with DB check."""
    try:
        await asyncio.wait_for(asyncio.to_thread(_db_health_check), timeout=5.0)
        return {"status": "alive", "db": "ok"}
    except Exception as e:
        raise HTTPException(
            status_code=503,
            detail={"status": "degraded", "db": "error", "error": str(e)},
        )


@app.get("/readyz")
async def readyz():
    """Kubernetes readiness probe — all dependencies available."""
    checks: dict[str, str] = {}
    all_ok = True

    try:
        await asyncio.wait_for(asyncio.to_thread(_db_health_check), timeout=5.0)
        checks["db"] = "ok"
    except Exception as e:
        checks["db"] = f"error: {e}"
        all_ok = False

    try:
        result = await asyncio.wait_for(
            asyncio.to_thread(_qdrant_health_check), timeout=5.0
        )
        checks["qdrant"] = result
    except Exception as e:
        checks["qdrant"] = f"error: {e}"
        all_ok = False

    try:
        result = await asyncio.wait_for(
            asyncio.to_thread(_redis_health_check), timeout=5.0
        )
        checks["redis"] = result
    except Exception as e:
        checks["redis"] = f"error: {e}"
        # Redis is optional — don't fail readiness

    if not all_ok:
        raise HTTPException(
            status_code=503,
            detail={"status": "not_ready", **checks},
        )
    return {"status": "ready", **checks}


