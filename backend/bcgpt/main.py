def _init_embeddings(app: FastAPI) -> None:
    """Set up the embedding function and reranking model."""
    cfg = app.state.config

    try:
        if cfg.RAG_EMBEDDING_MODEL_URI:
            app.state.ef = None
        else:
            app.state.ef = get_ef(
                cfg.RAG_EMBEDDING_ENGINE,
                cfg.RAG_EMBEDDING_MODEL,
                RAG_EMBEDDING_MODEL_AUTO_UPDATE,
            )

        app.state.rf = get_rf(
            cfg.RAG_RERANKING_MODEL,
            RAG_RERANKING_MODEL_AUTO_UPDATE,
            uri=cfg.RAG_RERANKING_MODEL_URI,
            api_key=cfg.RAG_RERANKING_MODEL_API_KEY,
        )
    except Exception as e:
        log.error(f"Error updating models: {e}")

    if cfg.RAG_EMBEDDING_MODEL_URI:
        app.state.EMBEDDING_FUNCTION = get_embedding_function(
            "openai",
            cfg.RAG_EMBEDDING_MODEL,
            None,
            cfg.RAG_EMBEDDING_MODEL_URI,
            cfg.RAG_EMBEDDING_MODEL_API_KEY,
            cfg.RAG_EMBEDDING_BATCH_SIZE,
        )
        if app.state.EMBEDDING_FUNCTION is None:
            log.warning(
                "Embedding function could not be created for URI-based model. "
                "Vector DB features will be unavailable."
            )
    else:
        if app.state.ef is None and cfg.RAG_EMBEDDING_ENGINE == "":
            log.warning(
                "Local embedding model failed to load. "
                "Vector DB features will be unavailable until the model is configured."
            )
            app.state.EMBEDDING_FUNCTION = None
        else:
            api_url = (
                cfg.RAG_OPENAI_API_BASE_URL
                if cfg.RAG_EMBEDDING_ENGINE == "openai"
                else cfg.RAG_OLLAMA_BASE_URL
            )
            api_key = (
                cfg.RAG_OPENAI_API_KEY
                if cfg.RAG_EMBEDDING_ENGINE == "openai"
                else cfg.RAG_OLLAMA_API_KEY
            )
            app.state.EMBEDDING_FUNCTION = get_embedding_function(
                cfg.RAG_EMBEDDING_ENGINE,
                cfg.RAG_EMBEDDING_MODEL,
                app.state.ef,
                api_url,
                api_key,
                cfg.RAG_EMBEDDING_BATCH_SIZE,
            )


