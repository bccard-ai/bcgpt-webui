@app.post("/api/chat/generations/{generation_id}/stop")
async def stop_chat_generation(
    generation_id: str,
    form_data: ChatGenerationBindingForm,
    user=Depends(get_verified_user),
):
    normalized_generation_id, normalized_chat_id, normalized_message_id = (
        await _verified_generation_binding(
            generation_id, form_data.chat_id, form_data.message_id, user.id
        )
    )
    durable_stop = await asyncio.to_thread(
        ChatGenerations.request_stop,
        generation_id=normalized_generation_id,
        user_id=user.id,
        chat_id=normalized_chat_id,
        assistant_message_id=normalized_message_id,
    )
    if durable_stop.kind == "different_generation":
        # Do not disclose whether a conflicting generation belongs to another
        # user or chat.
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Chat generation authority not found",
        )

    live_stop = None
    generation = durable_stop.generation
    if durable_stop.kind == "accepted":
        live_stop = await stop_generation(
            normalized_generation_id,
            owner_id=user.id,
            chat_id=normalized_chat_id,
            message_id=normalized_message_id,
        )
        if live_stop is not None and live_stop.get("stopped"):
            generation = await asyncio.to_thread(
                ChatGenerations.terminalize,
                normalized_generation_id,
                user.id,
                "stopped",
                "user_requested",
            )
        elif generation.task_id is None:
            # A Stop that wins before provider task binding is a terminal
            # tombstone. The later binder must observe it and refuse dispatch.
            generation = await asyncio.to_thread(
                ChatGenerations.terminalize,
                normalized_generation_id,
                user.id,
                "stopped",
                "user_requested_before_task_binding",
            )

    if generation is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Could not confirm chat generation stop",
        )

    terminal = generation.status in ("completed", "stopped", "error", "timed_out")
    stopped = generation.status == "stopped"
    observed = bool(live_stop and live_stop.get("observed"))
    if terminal:
        await asyncio.to_thread(
            Chats.upsert_message_to_chat_by_id_and_message_id,
            normalized_chat_id,
            normalized_message_id,
            {
                "done": True,
                "generationId": normalized_generation_id,
                "generationStatus": generation.status,
                "terminalReason": generation.terminal_reason,
            },
        )

    receipt = {
        "status": "observed" if observed else durable_stop.kind,
        "accepted": durable_stop.kind in ("accepted", "already_terminal"),
        "observed": observed,
        "terminal": terminal,
        "stopped": stopped,
        "durable": True,
        "task_id": generation.task_id,
        "generation_id": generation.generation_id,
        "chat_id": generation.chat_id,
        "message_id": generation.assistant_message_id,
        "generation": _public_generation_payload(generation),
    }
    replay = await asyncio.to_thread(
        ChatGenerations.get_replay_snapshot, normalized_generation_id, user.id
    )
    receipt["generation"]["replay"] = _public_replay_payload(replay)
    return JSONResponse(
        receipt,
        status_code=(
            status.HTTP_202_ACCEPTED
            if receipt["accepted"] and not receipt["terminal"]
            else status.HTTP_200_OK
        ),
    )


