@app.get("/api/models")
async def get_models(request: Request, user=Depends(get_verified_user)):
    def _filter_models_for_user(models: list, user) -> list:
        filtered = []
        for model in models:
            if model.get("arena"):
                if has_access(
                    user.id,
                    type="read",
                    access_control=model.get("info", {})
                    .get("meta", {})
                    .get("access_control", {}),
                ):
                    filtered.append(model)
                continue

            model_info = Models.get_model_by_id(model["id"])
            if model_info:
                if user.id == model_info.user_id or has_access(
                    user.id, type="read", access_control=model_info.access_control
                ):
                    filtered.append(model)
        return filtered

    all_models = await get_all_models(request, user=user)

    models = []
    for model in all_models:
        # Filter out filter pipelines
        if "pipeline" in model and model["pipeline"].get("type", None) == "filter":
            continue

        model_tags = [
            tag.get("name")
            for tag in model.get("info", {}).get("meta", {}).get("tags", [])
        ]
        tags = [tag.get("name") for tag in model.get("tags", [])]
        tags = list(set(model_tags + tags))
        model["tags"] = [{"name": tag} for tag in tags]
        models.append(model)

    model_order_list = request.app.state.config.MODEL_ORDER_LIST
    if model_order_list:
        order_map = {mid: i for i, mid in enumerate(model_order_list)}
        models.sort(key=lambda x: (order_map.get(x["id"], float("inf")), x["name"]))

    if user.role == "user" and not BYPASS_MODEL_ACCESS_CONTROL:
        models = _filter_models_for_user(models, user)

    log.debug(
        f"/api/models returned filtered models accessible to the user: "
        f"{json.dumps([m['id'] for m in models])}"
    )
    return {"data": models}


