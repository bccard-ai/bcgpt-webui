def _public_generation_payload(generation) -> dict[str, Any]:
    """Serialize generation authority without user IDs or request fingerprints."""

    return {
        "generation_id": generation.generation_id,
        "turn_id": generation.turn_id,
        "client_message_id": generation.client_message_id,
        "message_id": generation.assistant_message_id,
        "chat_id": generation.chat_id,
        "model_id": generation.model_id,
        "task_id": generation.task_id,
        "status": generation.status,
        "terminal_reason": generation.terminal_reason,
        "version": generation.version,
        "created_at": generation.created_at,
        "updated_at": generation.updated_at,
        "terminal_at": generation.terminal_at,
        "durable": True,
    }


def _public_replay_payload(replay) -> dict[str, Any] | None:
    if replay is None:
        return None
    return {
        "content": replay.content,
        "cursor": replay.last_sequence,
        "status": replay.status,
        "degraded": replay.degraded,
        "expires_at": replay.expires_at,
    }


def _generation_admission_response(result) -> dict[str, Any]:
    generation = result.generation
    terminal = generation.status in ("completed", "stopped", "error", "timed_out")
    return {
        "status": result.kind == "duplicate" and not terminal,
        "task_id": generation.task_id,
        "generation_id": generation.generation_id,
        "chat_id": generation.chat_id,
        "message_id": generation.assistant_message_id,
        "admission": {
            "status": result.kind,
            "accepted": result.kind == "duplicate" and not terminal,
            "terminal": terminal,
            "stopped": generation.status == "stopped",
            "durable": True,
            "generation": _public_generation_payload(generation),
        },
    }


async def _terminalize_admitted_generation(
    generation_request, status_value: str, reason: str
) -> None:
    """Persist both durable authority and the assistant's terminal projection."""

    generation = await asyncio.to_thread(
        ChatGenerations.terminalize,
        generation_request.generation_id,
        generation_request.user_id,
        status_value,
        reason,
    )
    if generation is None:
        return
    await asyncio.to_thread(
        Chats.upsert_message_to_chat_by_id_and_message_id,
        generation.chat_id,
        generation.assistant_message_id,
        {
            "done": True,
            "generationId": generation.generation_id,
            "generationStatus": generation.status,
            "terminalReason": generation.terminal_reason,
        },
    )


@app.post("/api/chat/completions")
async def chat_completion(
    request: Request,
    form_data: dict,
    user=Depends(get_verified_user),
):
    if not request.app.state.MODELS:
        await get_all_models(request, user=user)

    model_item = form_data.pop("model_item", {})
    tasks = form_data.pop("background_tasks", None)
    generation_request = None
    generation_admitted = False
    metadata: dict[str, Any] = {}

    try:
        model_id = form_data.get("model", None)
        if not model_item.get("direct", False):
            if model_id not in request.app.state.MODELS:
                raise Exception("Model not found")

            model = request.app.state.MODELS[model_id]
            model_info = Models.get_model_by_id(model_id)

            if not BYPASS_MODEL_ACCESS_CONTROL and user.role == "user":
                check_model_access(user, model)
        else:
            model = model_item
            model_info = None
            request.state.direct = True
            request.state.model = model

        try:
            generation_request = parse_chat_generation_request(
                form_data,
                user_id=user.id,
                model_id=model_id,
            )
        except ChatGenerationValidationError as exc:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=str(exc),
            ) from exc

        if generation_request is not None:
            try:
                await asyncio.to_thread(
                    verify_chat_generation_message_proof, generation_request
                )
            except ChatGenerationValidationError as exc:
                raise HTTPException(
                    status_code=status.HTTP_403_FORBIDDEN,
                    detail=str(exc),
                ) from exc

            admission = await asyncio.to_thread(
                ChatGenerations.admit,
                generation_id=generation_request.generation_id,
                turn_id=generation_request.turn_id,
                client_message_id=generation_request.client_message_id,
                assistant_message_id=generation_request.assistant_message_id,
                user_id=generation_request.user_id,
                chat_id=generation_request.chat_id,
                model_id=generation_request.model_id,
            )
            if admission.kind == "conflict":
                raise HTTPException(
                    status_code=status.HTTP_409_CONFLICT,
                    detail="Generation idempotency authority conflicts with an existing request",
                )
            if admission.kind != "accepted":
                if admission.generation.status in (
                    "completed",
                    "stopped",
                    "error",
                    "timed_out",
                ):
                    await asyncio.to_thread(
                        Chats.upsert_message_to_chat_by_id_and_message_id,
                        generation_request.chat_id,
                        generation_request.assistant_message_id,
                        {
                            "done": True,
                            "generationId": generation_request.generation_id,
                            "generationStatus": admission.generation.status,
                            "terminalReason": admission.generation.terminal_reason,
                        },
                    )
                return _generation_admission_response(admission)

            generation_admitted = True
            await asyncio.to_thread(
                Chats.upsert_message_to_chat_by_id_and_message_id,
                generation_request.chat_id,
                generation_request.assistant_message_id,
                {
                    "generationId": generation_request.generation_id,
                    "turnId": generation_request.turn_id,
                    "generationStatus": "admitted",
                    "done": False,
                },
            )

        metadata = {
            "user_id": user.id,
            "chat_id": form_data.pop("chat_id", None),
            "message_id": form_data.pop("id", None),
            "session_id": form_data.pop("session_id", None),
            "tool_ids": form_data.get("tool_ids", None),
            "tool_servers": form_data.pop("tool_servers", None),
            "skill_ids": form_data.pop("skill_ids", None),
            "files": form_data.get("files", None),
            "features": form_data.get("features", None),
            "variables": form_data.get("variables", None),
            "model": model,
            "direct": model_item.get("direct", False),
            **(
                {
                    "generation_id": generation_request.generation_id,
                    "turn_id": generation_request.turn_id,
                    "client_message_id": generation_request.client_message_id,
                }
                if generation_request is not None
                else {}
            ),
            **(
                {"function_calling": "native"}
                if form_data.get("params", {}).get("function_calling") == "native"
                or (
                    model_info
                    and model_info.params.model_dump().get("function_calling")
                    == "native"
                )
                else {}
            ),
        }

        # Stamp the request start for end-to-end AI-interaction latency (1.5).
        # `metadata` is the same dict later handed to process_chat_response.
        metadata["__chat_start_ts__"] = time.time()

        request.state.metadata = metadata
        form_data["metadata"] = metadata
        for field in ("generation_id", "turn_id", "client_message_id"):
            form_data.pop(field, None)

        form_data, metadata, events = await process_chat_payload(
            request, form_data, user, metadata, model
        )

    except HTTPException:
        if generation_request is not None and generation_admitted:
            await _terminalize_admitted_generation(
                generation_request,
                "error",
                "request_rejected",
            )
        raise
    except Exception as e:
        log.error(f"Error processing chat payload: {e}", exc_info=True)
        if generation_request is not None and generation_admitted:
            await _terminalize_admitted_generation(
                generation_request,
                "error",
                "payload_error",
            )
        if metadata.get("chat_id") and metadata.get("message_id"):
            Chats.upsert_message_to_chat_by_id_and_message_id(
                metadata["chat_id"],
                metadata["message_id"],
                {"error": {"content": str(e)}},
            )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )

    try:
        response = await chat_completion_handler(request, form_data, user)
        return await process_chat_response(
            request, response, form_data, user, metadata, model, events, tasks
        )
    except Exception as e:
        log.error(f"Error in chat completion handler/response: {e}", exc_info=True)
        if generation_request is not None and generation_admitted:
            await _terminalize_admitted_generation(
                generation_request,
                "error",
                "provider_dispatch_error",
            )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )


